                  status = 200,
                  body = [[{"access_token": "test_wi", "expires_in": 3600}]],
                }
              else
                error("bad test path provided??? " .. tostring(opts.path))
              end
            end,
          }
        end,
      }

      package.loaded["resty.luasocket.http"] = http
    end
  end)

  teardown(function()
    if not USE_REAL_GCP then
      package.loaded["resty.luasocket.http"] = nil
