      for i = 1, select("#", ...) do
        parts[i] = tostring(select(i, ...))
      end

      log_entries[#log_entries + 1] = {
        level = level,
        message = table.concat(parts),
      }
    end

    local ok, err = pcall(test_function, log_entries)
    ngx.log = original_log

    if not ok then
      error(err, 0)
    end
  end

